import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto('http://localhost:4316/', { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__ptyHello);
const h1 = await page.evaluate(() => window.__ptyHello);
console.log('first connect:', JSON.stringify(h1));
await page.click('[data-testid="xterm"]');
await page.keyboard.type('echo hello; echo "marker-$$"\n');
await page.waitForTimeout(800);
const buf = () => page.evaluate(() => { const t = window.__term; const b = t.buffer.active; let s = ''; for (let i = 0; i < b.length; i++) s += b.getLine(i).translateToString(true) + '\n'; return s; });
const before = await buf();
console.log('before reload contains hello:', /^hello$/m.test(before), '| marker:', before.match(/marker-\d+/)?.[0]);
await page.screenshot({ path: 'docs/proof/step5-terminal-before.png' });
await page.reload({ waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__ptyHello);
await page.waitForTimeout(800);
const h2 = await page.evaluate(() => window.__ptyHello);
console.log('after reload:', JSON.stringify(h2));
const after = await buf();
console.log('scrollback replayed (hello present):', /^hello$/m.test(after), '| same shell pid:', h1.pid === h2.pid, '| reattached:', h2.reattached);
await page.click('[data-testid="xterm"]');
await page.keyboard.type('echo "still-$$"\n');
await page.waitForTimeout(600);
console.log('same $$ after reload:', (await buf()).match(/still-\d+/)?.[0], 'vs', before.match(/marker-\d+/)?.[0]);
await page.screenshot({ path: 'docs/proof/step5-terminal-after-reload.png' });
console.log('page errors:', errs.length ? errs : 'none');
await browser.close();
